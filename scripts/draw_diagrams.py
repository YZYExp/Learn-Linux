class Diagram:
 def __init__(self, filename, title, subtitle, h=820):
  self.filename=filename; self.h=h
  self.parts=[f'<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="{h}" viewBox="0 0 1200 {h}" role="img" aria-labelledby="title desc">',f'<title id="title">{escape(title)}</title><desc id="desc">{escape(subtitle)}</desc>',f'<defs><marker id="arrow" markerWidth="9" markerHeight="9" refX="8" refY="4.5" orient="auto"><path d="M0,0 L9,4.5 L0,9" fill="{TEAL}"/></marker><marker id="arrowO" markerWidth="9" markerHeight="9" refX="8" refY="4.5" orient="auto"><path d="M0,0 L9,4.5 L0,9" fill="{ORANGE}"/></marker></defs>',f'<rect width="1200" height="{h}" fill="{BG}"/>',f'<style>text{{font-family:"Noto Sans SC","Noto Sans CJK SC",sans-serif}}.body{{font-size:20px}}.small{{font-size:17px;fill:{MUTED}}}</style>']
  self.text(54,60,title,32,weight=700)
  self.text(54,99,subtitle,19,color=MUTED)
  self.parts.append(f'<path d="M54 123H1146" stroke="{LINE}"/>')
 def text(self,x,y,txt,size=22,color=INK,anchor='start',weight=400):
  self.parts.append(f'<text x="{x}" y="{y}" font-size="{size}" fill="{color}" text-anchor="{anchor}" font-weight="{weight}">{escape(txt)}</text>')
 def box(self,x,y,w,h,title,lines=(),fill=WHITE,stroke=LINE):
  self.parts.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="15" fill="{fill}" stroke="{stroke}" stroke-width="1.5"/>')
  ty=y+35 if lines else y+h/2+8
  self.text(x+w/2,ty,title,23,anchor='middle',weight=600)
  for i,line in enumerate(lines):self.text(x+w/2,ty+31+27*i,line,18,color=MUTED,anchor='middle')
 def panel(self,x,y,w,h,title):
  self.parts.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="20" fill="none" stroke="{LINE}" stroke-dasharray="6 6"/>')
  self.text(x+20,y+33,title,19,color=MUTED)
 def arrow(self,x1,y1,x2,y2,label='',orange=False,dash=False):
  color=ORANGE if orange else TEAL
  marker='arrowO' if orange else 'arrow'
  self.parts.append(f'<path d="M{x1} {y1}L{x2} {y2}" fill="none" stroke="{color}" stroke-width="2.5" marker-end="url(#{marker})"'+(' stroke-dasharray="6 5"' if dash else '')+'/>')
  if label:self.text((x1+x2)/2,(y1+y2)/2-9,label,17,color=color,anchor='middle')
 def elbow(self,points,orange=False,dash=False):
  color=ORANGE if orange else TEAL; marker='arrowO' if orange else 'arrow'
  d='M'+'L'.join(f'{x},{y}' for x,y in points)
  self.parts.append(f'<path d="{d}" fill="none" stroke="{color}" stroke-width="2.5" marker-end="url(#{marker})"'+(' stroke-dasharray="6 5"' if dash else '')+'/>')
 def note(self,y,*lines):
  for i,t in enumerate(lines):self.text(64,y+i*28,t,19,color=MUTED)
 def finish(self):
  self.parts.append(f'<path d="M54 {self.h-65}H1146" stroke="{LINE}"/>')
  self.text(54,self.h-32,'原创机制示意 · 省略实现细节',17,color=MUTED)
  self.text(1146,self.h-32,self.filename.split('-')[0],17,color=MUTED,anchor='end')
  self.parts.append('</svg>')
  xml='\n'.join(self.parts); ET.fromstring(xml)
  (OUT/(self.filename+'.svg')).write_text(xml,encoding='utf-8')

